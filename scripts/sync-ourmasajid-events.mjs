#!/usr/bin/env node
// Syncs event cards from Our Masajid into content/events/.
//
// Run hourly (6am–10pm) by .github/workflows/ourmasajid-events-sync.yml.
// ICRR's events are managed in the Our Masajid admin
// (https://ourmasajid.com/admin/icrr/events), which publishes them through a
// public JSON feed with repeating events already expanded into one entry per
// date. Each entry with a flyer becomes a content/events/om-<id>.yml card
// matching the schema src/content.config.ts validates, and any om-*.yml file
// whose event has left the feed's window is removed.
//
// Never hand-edit an om-*.yml file — the next hourly run overwrites it. Edit
// the event in Our Masajid instead. Hand-authored cards (any filename not
// starting with "om-") are never touched by this script.
//
// The feed is the source of truth, so unlike the Google Calendar sync this
// replaced there's no scraping and nothing to second-guess: the cards mirror
// whatever the feed returns. A feed that can't be fetched fails the run
// without touching any file, so an Our Masajid outage leaves the current
// cards up rather than emptying the site.
//
// Legacy gcal-*.yml cards from the old Google Calendar sync are also treated
// as this script's own, so the first successful run replaces them.

import fs from 'node:fs';
import path from 'node:path';
import { dump } from 'js-yaml';

const API_BASE = (process.env.PUBLIC_OURMASAJID_API || 'https://ourmasajid.com').replace(/\/$/, '');
const SLUG = 'icrr';
const TZ = 'America/Chicago'; // Round Rock, TX — only used to pick the window start

const PREFIX = 'om-';
const LEGACY_PREFIX = 'gcal-';
const EVENTS_DIR = path.join(process.cwd(), 'content/events');

// The window of events that get cards. Starting a day back keeps a card up
// through the day after its event (the site itself moves a past dated card
// into "Previous Events" client-side); the lookahead keeps the gallery to
// what's coming up soon rather than months of a weekly program.
const LOOKBACK_DAYS = 1;
const LOOKAHEAD_DAYS = 10;

function isoDateInTz(date) {
  return new Intl.DateTimeFormat('en-CA', {
    timeZone: TZ,
    year: 'numeric',
    month: '2-digit',
    day: '2-digit',
  }).format(date); // en-CA gives YYYY-MM-DD directly
}

async function loadFeed() {
  const start = isoDateInTz(new Date(Date.now() - LOOKBACK_DAYS * 86400000));
  const days = LOOKBACK_DAYS + LOOKAHEAD_DAYS + 1;
  const url = `${API_BASE}/api/masajid/${SLUG}/events?start=${start}&days=${days}`;

  const res = await fetch(url, {
    headers: { Accept: 'application/json' },
    signal: AbortSignal.timeout(30000),
  });
  if (!res.ok) {
    throw new Error(`${url} responded ${res.status}: ${(await res.text()).slice(0, 300)}`);
  }
  const body = await res.json();
  if (!Array.isArray(body?.events)) {
    throw new Error(`${url} returned no events array`);
  }
  return body.events;
}

// "Thu, Oct 22 · 8:00 PM – 9:00 PM", the same line the calendar sync wrote.
// The feed preformats every label in the masjid's timezone, so nothing here
// depends on the timezone of the machine running the sync.
function formatDetail(ev) {
  if (!ev.endTime) return `${ev.dateLabel} · ${ev.startTime}`;
  if (!ev.endDate || ev.endDate === ev.date) {
    return `${ev.dateLabel} · ${ev.startTime} – ${ev.endTime}`;
  }
  return `${ev.dateLabel} ${ev.startTime} – ${ev.endDateLabel} ${ev.endTime}`;
}

function cardFor(ev) {
  return {
    title: ev.title,
    detail: formatDetail(ev),
    image: ev.imageUrl,
    section: 'gallery',
    schedule: 'dated',
    // A multi-day event lists its last day too, so the card archives only
    // once the whole event is over.
    dates: ev.endDate && ev.endDate !== ev.date ? `${ev.date},${ev.endDate}` : ev.date,
    show_on_homepage: true,
  };
}

function ownedFiles() {
  return fs
    .readdirSync(EVENTS_DIR)
    .filter((f) => (f.startsWith(PREFIX) || f.startsWith(LEGACY_PREFIX)) && /\.ya?ml$/.test(f));
}

async function main() {
  const events = await loadFeed();

  const header =
    `# Auto-generated by scripts/sync-ourmasajid-events.mjs from Our Masajid.\n` +
    `# Do not hand-edit — the next hourly sync overwrites this file.\n` +
    `# Edit the event instead: https://ourmasajid.com/admin/${SLUG}/events\n`;

  const keep = new Set();
  let written = 0;
  let skippedNoImage = 0;

  for (const ev of events) {
    // content.config.ts requires `image`; an event without a flyer still
    // shows on ourmasajid.com, just not as a card here.
    if (!ev.imageUrl) {
      console.warn(`skipping "${ev.title}" (${ev.date}) — no banner image in Our Masajid`);
      skippedNoImage++;
      continue;
    }
    const filename = `${PREFIX}${ev.id}.yml`;
    keep.add(filename);
    fs.writeFileSync(path.join(EVENTS_DIR, filename), header + dump(cardFor(ev), { lineWidth: 100 }));
    written++;
  }

  let deleted = 0;
  for (const filename of ownedFiles()) {
    if (keep.has(filename)) continue;
    fs.unlinkSync(path.join(EVENTS_DIR, filename));
    deleted++;
  }

  console.log(
    `Our Masajid sync: ${written} written, ${skippedNoImage} skipped (no image), ${deleted} removed, ${events.length} events in window`,
  );
}

main().catch((err) => {
  console.error(err);
  process.exit(1);
});
